-- Esquema do banco H2. Executado automaticamente na inicialização.
-- IF NOT EXISTS: rodar de novo não apaga o histórico.

CREATE TABLE IF NOT EXISTS medicao (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id  VARCHAR(20)  NOT NULL,
    tipo       VARCHAR(20)  NOT NULL,
    valor      DOUBLE       NOT NULL,
    data_hora  TIMESTAMP    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_medicao_sensor ON medicao (sensor_id, data_hora);

CREATE TABLE IF NOT EXISTS alerta (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id         VARCHAR(20)  NOT NULL,
    tipo              VARCHAR(20)  NOT NULL,
    nivel             VARCHAR(10)  NOT NULL,
    valor_previsto    DOUBLE       NOT NULL,
    limite_estourado  DOUBLE       NOT NULL,
    estrategia        VARCHAR(40)  NOT NULL,
    data_hora         TIMESTAMP    NOT NULL
);
